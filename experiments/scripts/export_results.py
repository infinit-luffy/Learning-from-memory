#!/usr/bin/env python3
"""Export W1.2 results from run artifacts into a small, version-controlled set.

`experiments/logs/` holds ~500 MB of run artifacts (model checkpoints, hydra
output, console logs) and is gitignored.  The *results* are 48 KB and belong in
the repo, so they can be read and re-analysed without the server.

Writes to `experiments/results/`:
    curves/<task>_s<seed>.csv   learning curve (step, episode_reward)
    final_eval.json             final checkpoint, 30-episode re-evaluation
    summary.csv                 one row per (task, seed) with key checkpoints
    table_v.md                  rendered tables (same content as w12_report.py)

Usage:  python experiments/scripts/export_results.py
"""
from __future__ import annotations

import argparse
import csv
import json
import shutil
import statistics
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOG_ROOT = ROOT / "experiments" / "logs"
OUT = ROOT / "experiments" / "results"
REPORT = ROOT / "experiments" / "scripts" / "w12_report.py"

CHECKPOINTS = [50_000, 100_000, 200_000, 250_000, 300_000, 375_000, 400_000, 500_000]


def read_curve(path):
    with open(path) as f:
        return [(int(float(r["step"])), float(r["episode_reward"]))
                for r in csv.DictReader(f)]


def at(curve, step):
    cand = [v for s, v in curve if s <= step]
    return cand[-1] if cand else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exp", default="w12_pixel")
    ap.add_argument("--also", default="w12_pixel_rerun",
                    help="extra exp_names whose curves to export (suffixed), "
                         "comma separated; they do not enter summary.csv")
    args = ap.parse_args()

    curves_dir = OUT / "curves"
    curves_dir.mkdir(parents=True, exist_ok=True)

    runs = []
    for exp in [args.exp] + args.also.split(",") if args.also else [args.exp]:
        for path in sorted(LOG_ROOT.glob(f"*/*/{exp}/eval.csv")):
            seed = int(path.parent.parent.name)
            task = path.parent.parent.parent.name
            suffix = "" if exp == args.exp else f"_{exp.split('_')[-1]}"
            shutil.copyfile(path, curves_dir / f"{task}_s{seed}{suffix}.csv")
            if exp == args.exp:
                runs.append((task, seed, read_curve(path)))
    if not runs:
        print("no eval.csv found under", LOG_ROOT)
        return 1

    src_json = LOG_ROOT / "final_eval.json"
    final = json.loads(src_json.read_text()) if src_json.exists() else {}
    if final:
        (OUT / "final_eval.json").write_text(json.dumps(final, indent=2, sort_keys=True))

    # Q2 zero-shot grid (R1). Small and central to the paper's §IV.C, so it
    # travels with the curves rather than staying in the run artifacts.
    ret_json = LOG_ROOT / "retention_eval.json"
    if ret_json.exists():
        shutil.copyfile(ret_json, OUT / "retention_eval.json")
        proc = subprocess.run(
            [sys.executable, str(ROOT / "experiments" / "scripts" / "retention_eval.py"),
             "--report"],
            cwd=str(ROOT), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        (OUT / "retention.md").write_text(
            "# R1 — zero-shot retention grid\n\n"
            "See `hippoact/TODO_RESULT.md` §R1: the paper's `hard/none` ratio is\n"
            "misleading here because easy-trained policies score *worse* on clean\n"
            "backgrounds than on their training distribution, so the denominator is\n"
            "itself out-of-distribution. `hard/easy` is the meaningful ratio.\n\n"
            "```\n" + proc.stdout + "```\n")

    # flat summary, one row per run
    with open(OUT / "summary.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["task", "seed"] + [f"step_{s}" for s in CHECKPOINTS]
                   + ["final_ckpt_30ep"])
        for task, seed, curve in runs:
            rec = final.get(f"{task}|{seed}|{args.exp}")
            w.writerow([task, seed]
                       + [("" if (v := at(curve, s)) is None else round(v, 1))
                          for s in CHECKPOINTS]
                       + [round(rec["reward"], 1) if rec else ""])

    # rendered tables, so the numbers are readable without running anything
    proc = subprocess.run(
        [sys.executable, str(REPORT), "--steps", "100000,250000,375000,500000"],
        cwd=str(ROOT), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    (OUT / "table_v.md").write_text(
        "# W1.2 — TD-MPC2-pixel baseline matrix\n\n"
        "Generated by `experiments/scripts/w12_report.py`; see\n"
        "`hippoact/TODO_RESULT.md` §W1.2 for derivation and caveats.\n\n"
        "```\n" + proc.stdout + "```\n")

    n_seeds = defaultdict(int)
    for task, seed, _ in runs:
        n_seeds[task] += 1
    print(f"exported {len(runs)} runs -> {OUT}")
    for task in sorted(n_seeds):
        print(f"  {task:<24} {n_seeds[task]} seeds")
    print(f"  final_eval entries: {len(final)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
